"""Map pinned source asset names; images are fetched on demand, not redistributed."""
import json
from pathlib import Path
root=Path(__file__).resolve().parents[1]
source=root/'tools/catalog-source'
legacy={1:'tell-your-world',126:'cinema',138:'king',248:'bug'}
music=json.loads((source/'musics.json').read_text(encoding='utf-8-sig'))
cards=json.loads((source/'cards.json').read_text(encoding='utf-8-sig'))
songs={legacy.get(m['id'],f"sekai-{m['id']}"):m['assetbundleName'] for m in music}
card_assets={c['id']:c['assetbundleName'] for c in cards}
lines=['// Generated by tools/import_artwork.py from pinned Global metadata.', 'const songAssetBundles = <String,String>{']
lines += [f'{json.dumps(k)}:{json.dumps(v)},' for k,v in songs.items()]
lines += ['};','const cardAssetBundles = <int,String>{']
lines += [f'{k}:{json.dumps(v)},' for k,v in card_assets.items()]
lines += ['};']
(root/'lib/src/artwork_data.g.dart').write_text('\n'.join(lines)+'\n',encoding='utf-8')
for table,data in [('songs',songs),('character_cards',card_assets)]:
    payload=json.dumps([{'id':k,'bundle':v} for k,v in data.items()]).replace("'","''")
    kind='text' if table=='songs' else 'integer'
    (root/f'supabase/artwork_{table}.sql').write_text(f"update public.{table} t set asset_bundle=x.bundle from jsonb_to_recordset('{payload}'::jsonb) x(id {kind},bundle text) where t.id=x.id;\n",encoding='utf-8')
print('Mapped',len(songs),'song jackets and',len(card_assets),'card asset bundles')
