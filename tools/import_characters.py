"""Generate roster/card metadata from the pinned Global master-data snapshot."""
import datetime as dt
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT/'tools/catalog-source'
def read(name):
    return json.loads((SOURCE/(name+'.json')).read_text(encoding='utf-8-sig'))
meta=read('provenance')
now=dt.datetime.fromisoformat(meta['as_of']).timestamp()*1000
units={'light_sound':'Leo/need','idol':'MORE MORE JUMP!','street':'Vivid BAD SQUAD','theme_park':'Wonderlands × Showtime','school_refusal':'25-ji, Nightcord de.','piapro':'Virtual Singer'}
profiles={p['characterId']:p for p in read('characterProfiles')}
characters=[]
for c in read('gameCharacters'):
    p=profiles[c['id']]
    characters.append({'id':c['id'],'name':' '.join(filter(None,[c.get('givenName'),c.get('firstName')])) if c['id']<=20 else ' '.join(filter(None,[c.get('firstName'),c.get('givenName')])), 'unit':units[c['unit']], 'birthday':p.get('birthday',''), 'voice':p.get('characterVoice',''), 'height':p.get('height',''), 'hobby':p.get('hobby','')})
cards=[{'id':c['id'],'character_id':c['characterId'],'title':c['prefix'],'rarity':c['cardRarityType'].replace('rarity_',''),'attribute':c['attr'],'released_at':dt.datetime.fromtimestamp(c['releaseAt']/1000,dt.timezone.utc).isoformat()} for c in read('cards') if c['releaseAt']<=now]
def dart(x): return json.dumps(x,ensure_ascii=False).replace('$',r'\$')
lines=["// Generated by tools/import_characters.py; Global source pinned in provenance.json.","part of 'characters.dart';",'const gameCharacters = <GameCharacter>[']
for c in characters:
    lines.append('GameCharacter('+','.join(dart(c[k]) for k in ['id','name','unit','birthday','voice','height','hobby'])+'),')
lines+= ['];','const gameCards = <CharacterCard>[']
for c in cards:
    lines.append('CharacterCard('+','.join(dart(c[k]) for k in ['id','character_id','title','rarity','attribute'])+'),')
lines+= ['];']
(ROOT/'lib/src/characters.g.dart').write_text('\n'.join(lines)+'\n',encoding='utf-8')
out=ROOT/'supabase/character-data';out.mkdir(exist_ok=True)
payload=json.dumps(characters,ensure_ascii=False).replace("'","''")
(out/'characters.sql').write_text(f"""insert into public.characters(id,name,unit_id,birthday,voice,height,hobby)
select x.id,x.name,u.id,x.birthday,x.voice,x.height,x.hobby from jsonb_to_recordset('{payload}'::jsonb) x(id integer,name text,unit text,birthday text,voice text,height text,hobby text) join public.units u on u.name=x.unit
on conflict(id) do update set name=excluded.name,unit_id=excluded.unit_id,birthday=excluded.birthday,voice=excluded.voice,height=excluded.height,hobby=excluded.hobby;
""",encoding='utf-8')
for n in range(0,len(cards),300):
    payload=json.dumps(cards[n:n+300],ensure_ascii=False).replace("'","''")
    (out/f'cards-{n//300:02}.sql').write_text(f"""insert into public.character_cards(id,character_id,title,rarity_id,attribute_id,released_at)
select id,character_id,title,rarity,attribute,released_at from jsonb_to_recordset('{payload}'::jsonb) x(id integer,character_id integer,title text,rarity text,attribute text,released_at timestamptz)
on conflict(id) do update set title=excluded.title,character_id=excluded.character_id,rarity_id=excluded.rarity_id,attribute_id=excluded.attribute_id,released_at=excluded.released_at;
""",encoding='utf-8')
(ROOT/'docs/character-provenance.json').write_text(json.dumps({**meta,'characters':len(characters),'released_cards':len(cards)},indent=2),encoding='utf-8')
print(len(characters),'characters;',len(cards),'released Global cards')
