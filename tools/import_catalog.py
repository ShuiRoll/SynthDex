"""Generate a reproducible Global/English catalog and normalized SQL from Sekai World data.
Run: python tools/import_catalog.py --download
Review generated SQL before applying to Supabase. Never contains credentials.
"""
import argparse
import datetime as dt
import json
from pathlib import Path
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'tools/catalog-source'
FILES = ['musics', 'musicDifficulties', 'musicTags', 'musicArtists', 'limitedTimeMusics']
REPO = 'Sekai-World/sekai-master-db-en-diff'
NAMES = {'vocaloid': 'Virtual Singer', 'light_music_club': 'Leo/need', 'idol': 'MORE MORE JUMP!', 'street': 'Vivid BAD SQUAD', 'theme_park': 'Wonderlands × Showtime', 'school_refusal': '25-ji, Nightcord de.', 'other': 'Other'}
COLORS = {'vocaloid': 0xff6f50b9, 'light_music_club': 0xff4f70ba, 'idol': 0xff55a78c, 'street': 0xff43889c, 'theme_park': 0xffac7b5d, 'school_refusal': 0xffb15e90, 'other': 0xff6f50b9}
DIFFICULTIES = ['easy', 'normal', 'hard', 'expert', 'master', 'append']
LEGACY = {1: 'tell-your-world', 248: 'bug', 126: 'cinema', 138: 'king'}

def fetch(url):
    req = urllib.request.Request(url, headers={'User-Agent': 'SynthDex-Catalog-Importer'})
    with urllib.request.urlopen(req, timeout=60) as response:
        return json.load(response)

def generate(download=False):
    SOURCE.mkdir(parents=True, exist_ok=True)
    meta_path = SOURCE / 'provenance.json'
    if download:
        commit = fetch(f'https://api.github.com/repos/{REPO}/commits/main')['sha']
        for name in FILES:
            data = fetch(f'https://raw.githubusercontent.com/{REPO}/{commit}/{name}.json')
            (SOURCE / f'{name}.json').write_text(json.dumps(data, ensure_ascii=False), encoding='utf-8')
        meta_path.write_text(json.dumps({'repository': REPO, 'commit': commit, 'as_of': dt.datetime.now(dt.timezone.utc).isoformat()}, indent=2), encoding='utf-8')
    provenance = json.loads(meta_path.read_text(encoding='utf-8'))
    now = dt.datetime.fromisoformat(provenance['as_of']).timestamp() * 1000
    data = {name: json.loads((SOURCE / f'{name}.json').read_text(encoding='utf-8-sig')) for name in FILES}
    artists = {a['id']: a['name'] for a in data['musicArtists']}
    songs = []
    for music in data['musics']:
        mid = music['id']
        tags = list(dict.fromkeys(t['musicTag'] for t in data['musicTags'] if t['musicId'] == mid and t['musicTag'] in NAMES))
        if not tags:
            tags = ['other']  # Limited-event medleys have only the all tag.
        levels = [0] * 6
        for chart in data['musicDifficulties']:
            if chart['musicId'] == mid:
                index = DIFFICULTIES.index(chart['musicDifficulty'])
                assert levels[index] == 0, f'Duplicate chart: {mid}'
                levels[index] = chart['playLevel']
        limits = [x for x in data['limitedTimeMusics'] if x['musicId'] == mid]
        available = mid not in {241, 290} and music['publishedAt'] <= now and (not limits or any(x['startAt'] <= now < x['endAt'] for x in limits))
        # Prefer a SEKAI unit for the presentation color; retain every tag for filtering.
        primary = next((t for t in tags if t not in ['vocaloid', 'other']), tags[0])
        songs.append({'id': LEGACY.get(mid, f'sekai-{mid}'), 'game_id': mid, 'title': music['title'], 'artist': artists[music['creatorArtistId']] if 'creatorArtistId' in music else music['creator'], 'units': [NAMES[t] for t in tags], 'color': COLORS[primary], 'levels': levels, 'available': available and any(levels), 'published_at': dt.datetime.fromtimestamp(music['publishedAt']/1000, dt.timezone.utc).isoformat(), 'search_alias': {248: 'Bug Kairiki Bear', 126: 'Cinema', 1: 'Hatsune Miku'}.get(mid, '') + ' ' + music['pronunciation']})
    assert len({s['id'] for s in songs}) == len(songs)
    def dart(value):
        return json.dumps(value, ensure_ascii=False).replace('$', r'\$')
    lines = ["// Generated by tools/import_catalog.py. Do not edit by hand.", "part of 'store.dart';", f"const catalogAsOf = {dart(provenance['as_of'][:10])};", "const catalogRegion = 'Global / EN';", 'const bundledSongs = <Song>[']
    for s in songs:
        lines.append(f"  Song({dart(s['id'])}, {dart(s['title'])}, {dart(s['artist'])}, {dart(' · '.join(s['units']))}, {s['color']}, {dart(s['levels'])}, units: {dart(s['units'])}, available: {str(s['available']).lower()}, searchAlias: {dart(s['search_alias'])}),")
    lines.append('];')
    (ROOT / 'lib/src/catalog.g.dart').write_text('\n'.join(lines)+'\n', encoding='utf-8')
    out = ROOT / 'supabase/catalog-data'
    out.mkdir(exist_ok=True)
    for old in out.glob('batch-*.sql'):
        old.unlink()
    for batch in range(0, len(songs), 100):
        payload = json.dumps(songs[batch:batch+100], ensure_ascii=False).replace("'", "''")
        sql = f"""begin;
create temp table imported on commit drop as select * from jsonb_to_recordset('{payload}'::jsonb) as x(id text,game_id integer,title text,artist text,units jsonb,color bigint,levels jsonb,available boolean,published_at timestamptz,search_alias text);
insert into public.artists(name) select distinct artist from imported on conflict(name) do nothing;
insert into public.units(name) select distinct jsonb_array_elements_text(units) from imported on conflict(name) do nothing;
insert into public.songs(id,title,color,artist_id,game_id,available,published_at,search_alias)
select i.id,i.title,i.color,a.id,i.game_id,i.available,i.published_at,i.search_alias from imported i join public.artists a on a.name=i.artist
on conflict(id) do update set title=excluded.title,color=excluded.color,artist_id=excluded.artist_id,game_id=excluded.game_id,available=excluded.available,published_at=excluded.published_at,search_alias=excluded.search_alias;
delete from public.song_units where song_id in (select id from imported);
insert into public.song_units(song_id,unit_id) select i.id,u.id from imported i cross join lateral jsonb_array_elements_text(i.units) tag(name) join public.units u on u.name=tag.name;
insert into public.charts(song_id,difficulty,level) select i.id,(c.ordinality-1)::integer,c.value::integer from imported i cross join lateral jsonb_array_elements_text(i.levels) with ordinality c(value,ordinality) where c.value::integer>0
on conflict(song_id,difficulty) do update set level=excluded.level;
commit;
"""
        (out / f'batch-{batch//100:02}.sql').write_text(sql, encoding='utf-8')
    # Retire absent songs without deleting anyone's progress or chart references.
    ids = ','.join("'"+s['id']+"'" for s in songs)
    (out / 'retire-missing.sql').write_text(f'update public.songs set available=false where id not in ({ids});\n', encoding='utf-8')
    active = [s for s in songs if s['available']]
    report = {**provenance, 'source_songs': len(songs), 'playable_songs': len(active), 'playable_charts': sum(sum(l>0 for l in s['levels']) for s in active), 'append_charts': sum(s['levels'][5]>0 for s in active), 'excluded': [{'id': s['game_id'], 'title': s['title']} for s in songs if not s['available']]}
    (ROOT / 'docs/catalog-provenance.json').write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding='utf-8')
    print(json.dumps(report, ensure_ascii=False))

if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--download', action='store_true')
    generate(parser.parse_args().download)


